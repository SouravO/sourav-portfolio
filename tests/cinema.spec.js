import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

const audioState = async page => page.evaluate(async () => {
  const { default: engine } = await import('/src/audio/audioEngine.js')
  return { created: !!engine.ctx, state: engine.ctx?.state, playing: engine.isPlayingBgm, timer: engine.timerId, volume: engine.volume, energy: engine.getFrequencyData().reduce((a, b) => a + b, 0) }
})

test('first visit offers sound, traps focus, plays a silent title sequence and remembers entry', async ({ page }) => {
  await page.goto('/')
  const intro = page.getByRole('dialog', { name: /Every build has a story/ })
  await expect(intro).toBeVisible()
  expect((await audioState(page)).created).toBe(false)
  const viewport = page.viewportSize()
  const frame = await intro.boundingBox()
  expect(frame.width).toBe(viewport.width)
  expect(frame.height).toBe(viewport.height)
  await expect(page.locator('.cinema-content')).toHaveAttribute('inert', '')
  await expect(page.getByRole('button', { name: 'Skip intro' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Enter silently' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Skip intro' })).toBeFocused()
  const results = await new AxeBuilder({ page }).analyze()
  expect(results.violations).toEqual([])
  await page.screenshot({ path: 'test-results/cinema-invitation.png' })
  await page.getByRole('button', { name: 'Enter silently' }).click()
  await expect(page.locator('.opening-screen')).toHaveClass(/phase-playing/)
  await expect(page.locator('.opening-signature')).toHaveCSS('opacity', '1', { timeout: 4500 })
  await page.screenshot({ path: 'test-results/cinema-title.png' })
  await expect(page.getByRole('dialog')).toHaveCount(0, { timeout: 6500 })
  expect((await audioState(page)).created).toBe(false)
  await expect(page.locator('.cinema-content')).not.toHaveAttribute('inert')
  await expect(page.getByRole('heading', { level: 1, name: /Ideas into real products/ })).toBeVisible()
  expect(await page.evaluate(() => sessionStorage.getItem('sourav_opening_seen'))).toBe('true')
  await page.reload()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('sound starts from a click, produces audio, mutes, pauses, and stops when the tab is hidden', async ({ page }) => {
  await page.goto('/#work')
  expect((await audioState(page)).created).toBe(false)
  await page.getByRole('button', { name: 'Replay cinematic opening' }).click()
  await page.getByRole('button', { name: 'Enter with sound' }).click()
  await expect.poll(async () => (await audioState(page)).state).toBe('running')
  await expect.poll(async () => (await audioState(page)).energy).toBeGreaterThan(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Pause soundtrack' })).toBeVisible()
  await page.getByRole('button', { name: 'Mute soundtrack' }).click()
  expect((await audioState(page)).volume).toBe(0)
  await expect(page.getByRole('button', { name: 'Unmute soundtrack' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Unmute soundtrack' }).click()
  await page.getByRole('button', { name: 'Pause soundtrack' }).click()
  await expect.poll(async () => (await audioState(page)).state).toBe('suspended')
  expect((await audioState(page)).timer).toBeNull()
  await page.getByRole('button', { name: 'Play soundtrack' }).click()
  await expect.poll(async () => (await audioState(page)).playing).toBe(true)
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, get: () => true })
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect.poll(async () => (await audioState(page)).state).toBe('suspended')
  await expect(page.getByRole('button', { name: 'Play soundtrack' })).toBeVisible()
  expect((await audioState(page)).playing).toBe(false)
  await page.evaluate(() => { delete document.hidden })
  await page.getByRole('button', { name: 'Play soundtrack' }).click()
  await expect.poll(async () => (await audioState(page)).playing).toBe(true)
  await page.getByRole('link', { name: 'Read case study for Check Your Deals', exact: true }).click()
  await expect.poll(async () => (await audioState(page)).state).toBe('suspended')
})

test('reduced motion and deep links bypass the opening; replay remains optional on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 667 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Replay cinematic opening' }).click()
  await expect(page.getByRole('dialog')).toContainText('Reduced motion is on')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/cinema-mobile.png' })
  await page.getByRole('button', { name: 'Enter silently' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/work/day-one-crm')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('heading', { level: 1, name: 'Day One CRM' })).toBeVisible()
})

test('missing audio support leaves the portfolio and silent opening usable', async ({ page }) => {
  await page.addInitScript(() => { window.AudioContext = undefined; window.webkitAudioContext = undefined })
  await page.goto('/?mode=chat#workspace')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Play soundtrack' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Sound could not start' })).toBeVisible()
  await page.getByRole('button', { name: 'Replay cinematic opening' }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByLabel('Ask about my work', { exact: true })).toBeVisible()
})

